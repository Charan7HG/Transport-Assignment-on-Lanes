
CREATE TABLE lanes (
    id BIGINT PRIMARY KEY,
    origin VARCHAR(100) NOT NULL,
    destination VARCHAR(100) NOT NULL
);

CREATE TABLE transporters (
    id BIGINT PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE lane_quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lane_id BIGINT NOT NULL,
    transporter_id BIGINT NOT NULL,
    quote_amount NUMERIC(12, 2) NOT NULL,

    CONSTRAINT fk_lane_quote_lane
        FOREIGN KEY (lane_id) REFERENCES lanes(id),

    CONSTRAINT fk_lane_quote_transporter
        FOREIGN KEY (transporter_id) REFERENCES transporters(id),

    CONSTRAINT uq_lane_transporter
        UNIQUE (lane_id, transporter_id),

    CONSTRAINT chk_quote_positive
        CHECK (quote_amount > 0)
);
